// RetryInfo describes SePay's automatic retries of a pending request.
type RetryInfo struct {
	RetriesCount int `json:"retries_count"`
	MaxRetries   int `json:"max_retries"`
	// NextRetryAt is "YYYY-MM-DD HH:mm:ss" in Vietnam time. nil means no retry is
	// scheduled any more and the final result is being settled.
	NextRetryAt *string `json:"next_retry_at"`
}

// NextRetryTime parses NextRetryAt. ok is false when it is nil or malformed.
func (r *RetryInfo) NextRetryTime() (t time.Time, ok bool) {
	if r == nil || r.NextRetryAt == nil {
		return time.Time{}, false
	}
	t, err := time.ParseInLocation(dateTimeLayout, *r.NextRetryAt, vnZone)
	return t, err == nil
}

// unconfirmedMessage is the Failed message meaning the outcome is unknown.
const unconfirmedMessage = "Hệ thống chưa xác nhận được kết quả phát hành với nhà cung cấp hóa đơn"

// ProcessResult is the status of an asynchronous create/adjust/replace/issue request.
type ProcessResult struct {
	ReferenceCode string        `json:"reference_code"`
	Status        ProcessStatus `json:"status"`
	Message       string        `json:"message"`
	Retry         *RetryInfo    `json:"retry"`   // only while Pending after a transient failure
	Invoice       *Invoice      `json:"invoice"` // set when Status is Success
}

// Done reports whether the request reached a final status (Success or Failed).
func (r *ProcessResult) Done() bool {
	return r.Status == StatusSuccess || r.Status == StatusFailed
}

// Unconfirmed reports whether SePay could not confirm the outcome with the
// invoice provider. The invoice may already be issued: do NOT resend; contact
// SePay with the tracking code instead.
func (r *ProcessResult) Unconfirmed() bool {
	return strings.Contains(r.Message, unconfirmedMessage)
}

// ListInvoicesParams filters ListInvoices. All fields are optional.
type ListInvoicesParams struct {
	Page           int // default 1
	PerPage        int // default 10, max 100
	Source         Source
	DocumentTypes  []DocumentType
	SellerStoreXID string
}

// InvoiceFile is a downloaded invoice file.
type InvoiceFile struct {
	FileType FileType `json:"file_type"`
	FileName string   `json:"file_name"`
	Content  []byte   `json:"content"` // decoded from base64
}

// CreateInvoice submits an invoice (draft or issued, per IsDraft).
// Poll the result with WaitForCreate or GetCreateStatus.
func (c *Client) CreateInvoice(ctx context.Context, req *CreateInvoiceRequest) (*TrackingResult, error) {
	r := *req
	r.IssuedDate = issuedAt(r.IssuedDate)
	return c.submit(ctx, "/v1/invoices/create", &r, r.IssuedDate)
}

// AdjustInvoice creates an adjustment invoice for an issued invoice.
// Poll the result with WaitForCreate or GetCreateStatus.
func (c *Client) AdjustInvoice(ctx context.Context, req *AdjustInvoiceRequest) (*TrackingResult, error) {
	r := *req
	r.IssuedDate = issuedAt(r.IssuedDate)
	return c.submit(ctx, "/v1/invoices/adjust", &r, r.IssuedDate)
}

// ReplaceInvoice creates a replacement for an issued invoice.
// Poll the result with WaitForCreate or GetCreateStatus.
func (c *Client) ReplaceInvoice(ctx context.Context, req *ReplaceInvoiceRequest) (*TrackingResult, error) {
	r := *req
	r.IssuedDate = issuedAt(r.IssuedDate)
	return c.submit(ctx, "/v1/invoices/replace", &r, r.IssuedDate)
}

// issuedAt returns t, or now when zero, as the API receives it: Vietnam time,
// whole seconds.
func issuedAt(t time.Time) time.Time {
	if t.IsZero() {
		t = time.Now()
	}
	return t.In(vnZone).Truncate(time.Second)
}

// submit posts a create, adjust or replace request and records issued on the result.
func (c *Client) submit(ctx context.Context, path string, body any, issued time.Time) (*TrackingResult, error) {
	var out TrackingResult
	if err := c.do(ctx, http.MethodPost, path, nil, body, &out); err != nil {
		return nil, err
	}
	out.IssuedDate = issued
	return &out, nil
}

// IssueInvoice issues a draft invoice to the tax authority.
// Poll the result with WaitForIssue or GetIssueStatus.
func (c *Client) IssueInvoice(ctx context.Context, referenceCode string) (*TrackingResult, error) {
	body := map[string]string{"reference_code": referenceCode}
	var out TrackingResult
	if err := c.do(ctx, http.MethodPost, "/v1/invoices/issue", nil, body, &out); err != nil {
		return nil, err
	}
	return &out, nil
}

// GetCreateStatus returns the status of a create, adjust or replace request.
func (c *Client) GetCreateStatus(ctx context.Context, trackingCode string) (*ProcessResult, error) {
	return c.getStatus(ctx, "/v1/invoices/create/check/"+url.PathEscape(trackingCode))
}

// GetIssueStatus returns the status of an issue request.
func (c *Client) GetIssueStatus(ctx context.Context, trackingCode string) (*ProcessResult, error) {
	return c.getStatus(ctx, "/v1/invoices/issue/check/"+url.PathEscape(trackingCode))
}

func (c *Client) getStatus(ctx context.Context, path string) (*ProcessResult, error) {
	var out ProcessResult
	if err := c.do(ctx, http.MethodGet, path, nil, nil, &out); err != nil {
		return nil, err
	}
	return &out, nil
}

// GetInvoice returns an invoice by reference code. It returns an error
// satisfying IsNotFound when no invoice exists.
func (c *Client) GetInvoice(ctx context.Context, referenceCode string) (*Invoice, error) {
	var out Invoice
	if err := c.do(ctx, http.MethodGet, "/v1/invoices/"+url.PathEscape(referenceCode), nil, nil, &out); err != nil {
		return nil, err
	}
	return &out, nil
}

// ListInvoices returns a page of invoices. params may be nil.
func (c *Client) ListInvoices(ctx context.Context, params *ListInvoicesParams) (*List[Invoice], error) {
	q := url.Values{}
	if params != nil {
		pagination(q, params.Page, params.PerPage)
		setIf(q, "source", string(params.Source))
		setIf(q, "seller_store_xid", params.SellerStoreXID)
		if len(params.DocumentTypes) > 0 {
			types := make([]string, len(params.DocumentTypes))
			for i, t := range params.DocumentTypes {
				types[i] = strconv.Itoa(int(t))
			}
			q.Set("document_type", strings.Join(types, ","))
		}
	}
	var out List[Invoice]
	if err := c.do(ctx, http.MethodGet, "/v1/invoices", q, nil, &out); err != nil {
		return nil, err
	}
	return &out, nil
}

// DownloadInvoice downloads an issued invoice as PDF or XML.
func (c *Client) DownloadInvoice(ctx context.Context, trackingCode string, fileType FileType) (*InvoiceFile, error) {
	q := url.Values{"type": {string(fileType)}}
	var out InvoiceFile
	if err := c.do(ctx, http.MethodGet, "/v1/invoices/"+url.PathEscape(trackingCode)+"/download", q, nil, &out); err != nil {
		return nil, err
	}
	return &out, nil
}

// DeleteDraftInvoice permanently deletes a draft invoice.
func (c *Client) DeleteDraftInvoice(ctx context.Context, referenceCode string) error {
	return c.do(ctx, http.MethodPost, "/v1/invoices/delete/"+url.PathEscape(referenceCode), nil, nil, nil)
}

