// Item is an invoice line in a create, adjust or replace request.
//
// Fields whose zero value is meaningful (TaxRate, TaxAmount, SubAmount, Amount)
// are pointers; nil means "not sent". Use Ptr to set them.
type Item struct {
	LineNumber int      `json:"line_number,omitempty"`
	LineType   LineType `json:"line_type,omitempty"`
	ItemCode   string   `json:"item_code,omitempty"`
	ItemName   string   `json:"item_name"`
	Unit       string   `json:"unit,omitempty"`
	Quantity   float64  `json:"quantity,omitempty"` // up to 2 decimals; may be negative in adjustments
	UnitPrice  float64  `json:"unit_price,omitempty"`
	TaxRate    *TaxRate `json:"tax_rate,omitempty"` // required per line for VAT invoices; ignored for sales invoices
	// TaxAmount overrides the computed line tax. Sent as-is, never recalculated.
	TaxAmount                  *int64   `json:"tax_amount,omitempty"`
	DiscountTax                float64  `json:"discount_tax,omitempty"`                   // line discount in percent
	DiscountAmount             float64  `json:"discount_amount,omitempty"`                // line discount amount
	BeforeDiscountAndTaxAmount float64  `json:"before_discount_and_tax_amount,omitempty"` // for LineTypeDiscount
	SubAmount                  *float64 `json:"sub_amount,omitempty"`                     // adjustments only: amount before tax, after discount
	Amount                     *float64 `json:"amount,omitempty"`                         // adjustments only: amount after tax
}

// CreateInvoiceRequest is the body of POST /v1/invoices/create.
type CreateInvoiceRequest struct {
	TemplateCode      string        `json:"template_code"`  // from ProviderAccount.Templates
	InvoiceSeries     string        `json:"invoice_series"` // from ProviderAccount.Templates; must match the current year
	IssuedDate        time.Time     `json:"issued_date"`    // must be today; zero means time.Now()
	Currency          Currency      `json:"currency"`
	ProviderAccountID string        `json:"provider_account_id"`
	SellerStoreXID    string        `json:"seller_store_xid,omitempty"`
	ReferenceCode     string        `json:"reference_code,omitempty"` // unique; generated by SePay if empty
	PaymentMethod     PaymentMethod `json:"payment_method,omitempty"`
	// IsDraft creates a draft to be issued later with IssueInvoice. Drafts do not consume quota.
	IsDraft bool   `json:"is_draft"`
	Buyer   Buyer  `json:"buyer"`
	Items   []Item `json:"items"`
	Notes   string `json:"notes,omitempty"`
	// TotalAmount overrides the computed total (tax included). Sent as-is, never checked.
	TotalAmount *int64 `json:"total_amount,omitempty"`
}

// MarshalJSON formats IssuedDate as the API expects, defaulting to now.
func (r CreateInvoiceRequest) MarshalJSON() ([]byte, error) {
	type alias CreateInvoiceRequest
	issued := r.IssuedDate
	if issued.IsZero() {
		issued = time.Now()
	}
	return json.Marshal(struct {
		alias
		IssuedDate string `json:"issued_date"`
	}{alias(r), formatDateTime(issued)})
}

